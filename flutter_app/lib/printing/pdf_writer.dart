// Petit générateur PDF sans dépendance (polices standard Helvetica, encodage WinAnsi) :
// suffisant pour des rapports texte + tableaux + graphiques en barres, lisibles partout.
import 'dart:convert';
import 'dart:typed_data';

class PdfColor {
  const PdfColor(this.r, this.g, this.b);
  factory PdfColor.hex(int v) => PdfColor(((v >> 16) & 255) / 255, ((v >> 8) & 255) / 255, (v & 255) / 255);
  final double r, g, b;
  String get _rgb => '${_n(r)} ${_n(g)} ${_n(b)}';
}

enum PdfAlign { left, right, center }

/// Document A4 (595 × 842 points), origine en HAUT à gauche pour simplifier la mise en page.
class PdfDoc {
  static const width = 595.0;
  static const height = 842.0;
  final _pages = <StringBuffer>[];
  StringBuffer get _page => _pages.last;

  int get pageCount => _pages.length;
  void addPage() => _pages.add(StringBuffer());

  /// Largeur d'un texte en points.
  static double textWidth(String s, double size, {bool bold = false}) {
    final w = bold ? _helvBold : _helv;
    var t = 0;
    for (final c in _encode(s)) {
      t += c >= 32 ? w[c - 32] : 0;
    }
    return t * size / 1000;
  }

  /// Coupe un texte trop long avec « … ».
  static String fit(String s, double maxWidth, double size, {bool bold = false}) {
    if (textWidth(s, size, bold: bold) <= maxWidth) return s;
    var t = s;
    while (t.isNotEmpty && textWidth('$t…', size, bold: bold) > maxWidth) {
      t = t.substring(0, t.length - 1);
    }
    return '${t.trimRight()}…';
  }

  void text(double x, double y, String s, {double size = 10, bool bold = false, PdfColor color = const PdfColor(0, 0, 0), PdfAlign align = PdfAlign.left}) {
    final w = textWidth(s, size, bold: bold);
    final dx = switch (align) {
      PdfAlign.left => x,
      PdfAlign.right => x - w,
      PdfAlign.center => x - w / 2,
    };
    final bytes = _encode(s);
    final esc = StringBuffer();
    for (final b in bytes) {
      if (b == 0x28 || b == 0x29 || b == 0x5c) {
        esc.write('\\${String.fromCharCode(b)}');
      } else if (b < 32 || b > 126) {
        esc.write('\\${b.toRadixString(8).padLeft(3, '0')}');
      } else {
        esc.writeCharCode(b);
      }
    }
    _page.writeln('BT /${bold ? 'F2' : 'F1'} ${_n(size)} Tf ${color._rgb} rg ${_n(dx)} ${_n(height - y)} Td ($esc) Tj ET');
  }

  void rect(double x, double y, double w, double h, PdfColor fill) {
    _page.writeln('${fill._rgb} rg ${_n(x)} ${_n(height - y - h)} ${_n(w)} ${_n(h)} re f');
  }

  void line(double x1, double y1, double x2, double y2, {PdfColor color = const PdfColor(0.8, 0.8, 0.8), double width = 0.6}) {
    _page.writeln('${color._rgb} RG ${_n(width)} w ${_n(x1)} ${_n(height - y1)} m ${_n(x2)} ${_n(height - y2)} l S');
  }

  Uint8List save() {
    final objs = <String>[];
    // 1 catalogue, 2 pages, 3 Helvetica, 4 Helvetica-Bold, puis page/contenu par page.
    final kids = [for (var i = 0; i < _pages.length; i++) '${5 + i * 2} 0 R'].join(' ');
    objs.add('<< /Type /Catalog /Pages 2 0 R >>');
    objs.add('<< /Type /Pages /Kids [$kids] /Count ${_pages.length} >>');
    objs.add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>');
    objs.add('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>');
    for (var i = 0; i < _pages.length; i++) {
      final content = latin1.encode(_pages[i].toString());
      objs.add('<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] /Resources << /Font << /F1 3 0 R /F2 4 0 R >> >> /Contents ${6 + i * 2} 0 R >>');
      objs.add('<< /Length ${content.length} >>\nstream\n${_pages[i]}endstream');
    }
    final out = BytesBuilder();
    final offsets = <int>[];
    void w(String s) => out.add(latin1.encode(s));
    w('%PDF-1.4\n');
    for (var i = 0; i < objs.length; i++) {
      offsets.add(out.length);
      w('${i + 1} 0 obj\n${objs[i]}\nendobj\n');
    }
    final xref = out.length;
    w('xref\n0 ${objs.length + 1}\n0000000000 65535 f \n');
    for (final o in offsets) {
      w('${'$o'.padLeft(10, '0')} 00000 n \n');
    }
    w('trailer\n<< /Size ${objs.length + 1} /Root 1 0 R >>\nstartxref\n$xref\n%%EOF\n');
    return out.toBytes();
  }
}

